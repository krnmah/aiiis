def test_generate_with_provider_calls_named_provider(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    fake_provider = FakeProvider()
    monkeypatch.setattr(
        llm_service, "get_llm_provider_by_name", lambda name: fake_provider
    )

    text = llm_service.generate_with_provider(
        provider_name="openai",
        prompt="compare",
        system_prompt="brief",
        model="gpt-4o-mini",
    )

    assert text == "generated by fake provider"
    assert fake_provider.last_call == {
        "prompt": "compare",
        "system_prompt": "brief",
        "model": "gpt-4o-mini",
    }


def test_get_llm_provider_raises_for_unsupported_provider(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    llm_service.get_llm_provider.cache_clear()
    monkeypatch.setattr(
        llm_service,
        "get_settings",
        lambda: SimpleNamespace(llm_provider="unsupported"),
    )

    with pytest.raises(LLMProviderError, match="unsupported_llm_provider"):
        llm_service.get_llm_provider()

    llm_service.get_llm_provider.cache_clear()
